#!/usr/bin/env bash
# Phase 7: create the Keycloak single sign-on secrets and seal them for Git.
# Run on the utility server (dns.lab.local). Writes three SealedSecrets to ~/keycloak-sealed/:
#
#   realm-secrets-sealedsecret.yaml  -> components/keycloak/manifests/
#       keycloak/keycloak-realm-secrets: both OIDC client secrets + your Keycloak password
#   argocd-oidc-sealedsecret.yaml    -> components/argocd/manifests/
#       argocd/argocd-oidc-keycloak: Argo CD's client secret
#   grafana-oidc-sealedsecret.yaml   -> components/kube-prometheus-stack/manifests/
#       monitoring/grafana-oidc-keycloak: Grafana's client secret
#
# The client secrets are random and appear in two places (Keycloak and the app), so the
# three files belong together: re-running the script makes new secrets, and then all
# three must be committed again. Only this cluster can decrypt them, so they're safe in
# the public repo. Files go to your home folder, not this clone, so `git pull` can't clash.
set -euo pipefail

OUT="$HOME/keycloak-sealed"
mkdir -p "$OUT"

read -rsp "Password for your Keycloak user 'andrew': " PW; echo
read -rsp "Same again: " PW2; echo
[[ -n "$PW" && "$PW" == "$PW2" ]] || { echo "Passwords empty or don't match" >&2; exit 1; }

ARGOCD_SECRET=$(openssl rand -hex 32)
GRAFANA_SECRET=$(openssl rand -hex 32)

header() {
  echo "# $1, encrypted with Sealed Secrets."
  echo "# Generated by scripts/seal-keycloak-secrets.sh - only this cluster can decrypt it."
}

{
  header "Keycloak realm secrets (OIDC client secrets, andrew's password)"
  kubectl create secret generic keycloak-realm-secrets --namespace keycloak \
    --from-literal=argocd-client-secret="$ARGOCD_SECRET" \
    --from-literal=grafana-client-secret="$GRAFANA_SECRET" \
    --from-literal=andrew-password="$PW" \
    --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/realm-secrets-sealedsecret.yaml"

# Argo CD only reads Secrets referenced from argocd-cm ($<secret>:<key>) if they carry
# the label app.kubernetes.io/part-of=argocd.
{
  header "Argo CD's Keycloak client secret"
  kubectl create secret generic argocd-oidc-keycloak --namespace argocd \
    --from-literal=clientSecret="$ARGOCD_SECRET" --dry-run=client -o yaml \
  | kubectl label --local -f - app.kubernetes.io/part-of=argocd -o yaml \
  | kubeseal --format yaml
} > "$OUT/argocd-oidc-sealedsecret.yaml"

{
  header "Grafana's Keycloak client secret"
  kubectl create secret generic grafana-oidc-keycloak --namespace monitoring \
    --from-literal=client-secret="$GRAFANA_SECRET" \
    --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/grafana-oidc-sealedsecret.yaml"

unset PW PW2 ARGOCD_SECRET GRAFANA_SECRET
ls -l "$OUT"

cat <<'MSG'

Next, on the Mac (on the phase-7-keycloak branch):
  cd ~/GitHub/platform-gitops
  scp admin@172.16.79.10:keycloak-sealed/realm-secrets-sealedsecret.yaml components/keycloak/manifests/
  scp admin@172.16.79.10:keycloak-sealed/argocd-oidc-sealedsecret.yaml components/argocd/manifests/
  scp admin@172.16.79.10:keycloak-sealed/grafana-oidc-sealedsecret.yaml components/kube-prometheus-stack/manifests/
  then commit and push.
MSG
