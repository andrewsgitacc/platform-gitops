#!/usr/bin/env bash
# Phase 8: create Harbor's secrets and seal them for Git.
# Run on the utility server (needs kubeseal, openssl, jq and htpasswd - from the admin
# tools playbook). Writes three SealedSecrets to ~/harbor-sealed/:
#
#   harbor-secrets-sealedsecret.yaml   -> components/harbor/manifests/
#       harbor/harbor-secrets: admin password, Harbor's internal secrets, the registry's
#       htpasswd, and the Keycloak (OIDC) settings incl. Harbor's client secret
#   harbor-token-sealedsecret.yaml     -> components/harbor/manifests/
#       harbor/harbor-token: certificate + key Harbor signs registry tokens with
#   harbor-client-sealedsecret.yaml    -> components/keycloak/manifests/
#       keycloak/keycloak-harbor-client: the same client secret, for the Keycloak realm
#
# The three files belong together (the client secret is in two of them): re-running the
# script makes new values, and then all three must be committed again. Re-sealing after
# Harbor has stored data also changes secretKey, which makes stored secrets (users' CLI
# secrets, replication credentials) unreadable - fine for a fresh install, avoid it later.
# To replace only the token certificate: ./scripts/seal-harbor-secrets.sh --token-only
set -euo pipefail

for t in kubeseal openssl jq htpasswd; do
  command -v "$t" >/dev/null || { echo "$t not found: run labs/admin install_admin_tools.yml" >&2; exit 1; }
done

OUT="$HOME/harbor-sealed"
TOKEN_ONLY=false
[[ "${1:-}" == "--token-only" ]] && TOKEN_ONLY=true   # re-make only harbor-token
mkdir -p "$OUT"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

if ! $TOKEN_ONLY; then
echo "Password for Harbor's local 'admin' (8+ characters, upper and lower case and a digit):"
read -rsp "  password: " ADMIN_PW; echo
read -rsp "  same again: " PW2; echo
[[ -n "$ADMIN_PW" && "$ADMIN_PW" == "$PW2" ]] || { echo "Passwords empty or don't match" >&2; exit 1; }

REGISTRY_USER=harbor_registry_user          # must match registry.credentials.username
REGISTRY_PW=$(openssl rand -hex 16)
CLIENT_SECRET=$(openssl rand -hex 32)

# Harbor usernames come from the email claim: Keycloak "admin" becomes "admin@lab.local",
# because Harbor's own local user is already called "admin".
OIDC_JSON=$(jq -cn --arg secret "$CLIENT_SECRET" '{
  auth_mode: "oidc_auth",
  oidc_name: "Keycloak",
  oidc_endpoint: "https://keycloak.apps.lab.local/realms/platform",
  oidc_client_id: "harbor",
  oidc_client_secret: $secret,
  oidc_scope: "openid,profile,email,offline_access",
  oidc_user_claim: "email",
  oidc_groups_claim: "groups",
  oidc_admin_group: "platform-admins",
  oidc_verify_cert: true,
  oidc_auto_onboard: true
}')

header() {
  echo "# $1, encrypted with Sealed Secrets."
  echo "# Generated by scripts/seal-harbor-secrets.sh - only this cluster can decrypt it."
}

{
  header "Harbor's secrets"
  kubectl create secret generic harbor-secrets --namespace harbor \
    --from-literal=HARBOR_ADMIN_PASSWORD="$ADMIN_PW" \
    --from-literal=secretKey="$(openssl rand -hex 8)" \
    --from-literal=secret="$(openssl rand -hex 8)" \
    --from-literal=JOBSERVICE_SECRET="$(openssl rand -hex 8)" \
    --from-literal=REGISTRY_HTTP_SECRET="$(openssl rand -hex 8)" \
    --from-literal=CSRF_KEY="$(openssl rand -hex 16)" \
    --from-literal=REGISTRY_PASSWD="$REGISTRY_PW" \
    --from-literal=REGISTRY_HTPASSWD="$(htpasswd -nbB "$REGISTRY_USER" "$REGISTRY_PW" | head -1)" \
    --from-literal=CONFIG_OVERWRITE_JSON="$OIDC_JSON" \
    --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/harbor-secrets-sealedsecret.yaml"
fi

# Harbor only reads a PKCS#1 key ("BEGIN RSA PRIVATE KEY"); OpenSSL 3 writes PKCS#8 by
# default, hence -traditional.
openssl genrsa -traditional -out "$TMP/tls.key" 4096 2>/dev/null
openssl req -x509 -new -key "$TMP/tls.key" -days 3650 -subj "/CN=harbor-token-ca" \
  -out "$TMP/tls.crt"
{
  header "Harbor's registry token signing certificate"
  kubectl create secret generic harbor-token --namespace harbor \
    --from-file=tls.crt="$TMP/tls.crt" --from-file=tls.key="$TMP/tls.key" \
    --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/harbor-token-sealedsecret.yaml"

if ! $TOKEN_ONLY; then
{
  header "Harbor's Keycloak client secret"
  kubectl create secret generic keycloak-harbor-client --namespace keycloak \
    --from-literal=client-secret="$CLIENT_SECRET" \
    --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/harbor-client-sealedsecret.yaml"
fi

unset ADMIN_PW PW2 REGISTRY_PW CLIENT_SECRET OIDC_JSON
ls -l "$OUT"

cat <<'MSG'

Next, on the Mac (on the phase-8-harbor branch):
  cd ~/GitHub/platform-gitops
  scp admin@172.16.79.10:harbor-sealed/harbor-secrets-sealedsecret.yaml components/harbor/manifests/
  scp admin@172.16.79.10:harbor-sealed/harbor-token-sealedsecret.yaml components/harbor/manifests/
  scp admin@172.16.79.10:harbor-sealed/harbor-client-sealedsecret.yaml components/keycloak/manifests/
  then commit and push.
MSG
