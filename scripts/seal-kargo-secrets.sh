#!/usr/bin/env bash
# Phase 10: seal Kargo's secrets. Run on the utility server.
#
#   ./scripts/seal-kargo-secrets.sh                  everything below
#   ./scripts/seal-kargo-secrets.sh --api-only       only kargo-api (new admin password)
#   ./scripts/seal-kargo-secrets.sh --pipeline-only  only the sample-app pipeline's secrets
#
# Writes SealedSecrets to ~/kargo-sealed/:
#
#   kargo-api-sealedsecret.yaml -> components/kargo/manifests/
#       kargo/kargo-api: the built-in admin's password hash and token signing key.
#   git-sample-app-deploy-sealedsecret.yaml, harbor-image-sealedsecret.yaml,
#   harbor-pull-{dev,staging,prod}-sealedsecret.yaml -> kargo/sample-app/
#       sample-app/git-sample-app-deploy: lets Kargo push the stage/* branches of
#         sample-app-deploy. Fine-grained PAT "lab-kargo", repositories sample-app-deploy
#         and puppet-control-repo, permission "Contents: Read and write".
#       sample-app/harbor-image: lets Kargo's Warehouse list sample-app images.
#       sample-app-<stage>/harbor-pull: lets each stage's pods pull them.
#     Both Harbor secrets use one pull-only robot account, robot$sample-app+kargo, which
#     this script creates in Harbor (asks for Harbor's local admin password).
#
# Only this cluster can decrypt the files, so they're safe in the public repo.
set -euo pipefail
trap 'echo "FAILED at line $LINENO - check the files in ~/kargo-sealed before copying them" >&2' ERR

OUT="$HOME/kargo-sealed"
HARBOR=harbor.apps.lab.local
IMAGE_REPO="$HARBOR/sample-app/sample-app"
DEPLOY_REPO=https://github.com/andrewsgitacc/sample-app-deploy.git

usage() { sed -n '4,6p' "$0" | sed 's/^# *//'; exit 1; }

header() {
  echo "# $1, encrypted with Sealed Secrets."
  echo "# Generated by scripts/seal-kargo-secrets.sh - only this cluster can decrypt it."
}

seal_api() {
  local pw pw2 hash
  read -rsp "New password for Kargo's built-in admin: " pw; echo
  read -rsp "Same again: " pw2; echo
  [[ -n "$pw" && "$pw" == "$pw2" ]] || { echo "Passwords empty or different" >&2; exit 1; }
  # bcrypt; htpasswd writes \$2y\$, Kargo (Go) expects \$2a\$ - same algorithm.
  hash=$(htpasswd -nbBC 10 admin "$pw" | head -1 | cut -d: -f2- | sed 's/^\$2y\$/$2a$/')
  [[ "$hash" == '$2a$'* ]] || { echo "htpasswd didn't produce a bcrypt hash" >&2; exit 1; }
  {
    header "Kargo's admin account"
    kubectl create secret generic kargo-api --namespace kargo \
      --from-literal=ADMIN_ACCOUNT_PASSWORD_HASH="$hash" \
      --from-literal=ADMIN_ACCOUNT_TOKEN_SIGNING_KEY="$(openssl rand -base64 30)" \
      --dry-run=client -o yaml | kubeseal --format yaml
  } > "$OUT/kargo-api-sealedsecret.yaml"
}

# Prints "name secret" of a new pull-only robot account in the Harbor project sample-app.
create_robot() {
  local hpw resp code
  read -rsp "Harbor admin password: " hpw; echo >&2   # stdout is the result
  resp=$(curl -s -w '\n%{http_code}' -u "admin:$hpw" -H 'Content-Type: application/json' \
    -X POST "https://$HARBOR/api/v2.0/robots" -d '{
      "name": "kargo", "duration": -1, "level": "project",
      "description": "Kargo: discover and pull sample-app images",
      "permissions": [{"kind": "project", "namespace": "sample-app", "access": [
        {"resource": "repository", "action": "pull"}]}]}')
  code=$(tail -n1 <<<"$resp")
  case "$code" in
    201) head -n -1 <<<"$resp" | jq -r '"\(.name) \(.secret)"' ;;
    409) echo "Harbor already has robot\$sample-app+kargo. Delete it (Harbor -> Projects -> sample-app -> Robot Accounts) and run this again." >&2; return 1 ;;
    *)   echo "Harbor robot account: HTTP $code $(head -n -1 <<<"$resp")" >&2; return 1 ;;
  esac
}

seal_pipeline() {
  local token code robot robot_name robot_secret stage
  read -rsp "GitHub token lab-kargo (sample-app-deploy, Contents read/write): " token; echo
  [[ -n "$token" ]] || { echo "No token" >&2; exit 1; }
  # Check the token can write to the repo before sealing it.
  code=$(curl -s -o /tmp/kargo-repo.json -w '%{http_code}' -H "Authorization: Bearer $token" \
    https://api.github.com/repos/andrewsgitacc/sample-app-deploy)
  [[ "$code" == 200 ]] || { echo "The token can't read andrewsgitacc/sample-app-deploy (HTTP $code)" >&2; exit 1; }
  [[ "$(jq -r '.permissions.push' /tmp/kargo-repo.json)" == true ]] \
    || { echo "The token can't write to sample-app-deploy (needs Contents: Read and write)" >&2; exit 1; }
  rm -f /tmp/kargo-repo.json
  echo "The token can write to sample-app-deploy."

  robot=$(create_robot)
  robot_name=${robot%% *}; robot_secret=${robot#* }
  [[ -n "$robot_name" && -n "$robot_secret" && "$robot_name" != "$robot_secret" ]] \
    || { echo "No robot account name/secret from Harbor" >&2; exit 1; }
  echo "Created Harbor robot account $robot_name."

  {
    header "Kargo's GitHub token for sample-app-deploy"
    kubectl create secret generic git-sample-app-deploy --namespace sample-app \
      --from-literal=repoURL="$DEPLOY_REPO" \
      --from-literal=username=kargo \
      --from-literal=password="$token" \
      --dry-run=client -o yaml \
      | kubectl label --local -f - kargo.akuity.io/cred-type=git -o yaml \
      | kubeseal --format yaml
  } > "$OUT/git-sample-app-deploy-sealedsecret.yaml"

  {
    header "Kargo's Harbor credentials for the sample-app Warehouse"
    kubectl create secret generic harbor-image --namespace sample-app \
      --from-literal=repoURL="$IMAGE_REPO" \
      --from-literal=username="$robot_name" \
      --from-literal=password="$robot_secret" \
      --dry-run=client -o yaml \
      | kubectl label --local -f - kargo.akuity.io/cred-type=image -o yaml \
      | kubeseal --format yaml
  } > "$OUT/harbor-image-sealedsecret.yaml"

  for stage in dev staging prod; do
    {
      header "Image pull secret for Harbor in sample-app-$stage"
      kubectl create secret docker-registry harbor-pull --namespace "sample-app-$stage" \
        --docker-server="$HARBOR" --docker-username="$robot_name" --docker-password="$robot_secret" \
        --dry-run=client -o yaml | kubeseal --format yaml
    } > "$OUT/harbor-pull-$stage-sealedsecret.yaml"
  done
}

mode=all
case "${1:-}" in
  "") ;;
  --api-only) mode=api ;;
  --pipeline-only) mode=pipeline ;;
  *) usage ;;
esac

mkdir -p "$OUT"
[[ "$mode" == pipeline ]] || seal_api
[[ "$mode" == api ]] || seal_pipeline
ls -l "$OUT"

cat <<'MSG'

Next, on the Mac (on your branch), one scp for all files:
  cd ~/GitHub/platform-gitops
  scp -r admin@172.16.79.10:kargo-sealed /tmp/
then, in a separate block:
  cp /tmp/kargo-sealed/kargo-api-sealedsecret.yaml components/kargo/manifests/ 2>/dev/null || true
  cp /tmp/kargo-sealed/git-*.yaml /tmp/kargo-sealed/harbor-*.yaml kargo/sample-app/ 2>/dev/null || true
  rm -rf /tmp/kargo-sealed
  git status
and commit and push - merge only once the pull request shows that commit.
MSG
