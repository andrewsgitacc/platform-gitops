#!/usr/bin/env bash
# Phase 9: seal the two GitHub tokens CI needs. Run on the utility server.
# Writes two SealedSecrets to ~/ci-sealed/:
#
#   github-token-sealedsecret.yaml   -> components/arc-sample-app/manifests/
#       arc-runners/arc-github-token (github_token): lets ARC register runners on
#       sample-app. Fine-grained PAT, repository andrewsgitacc/sample-app,
#       permission "Administration: Read and write" (Metadata: read is added automatically).
#   renovate-token-sealedsecret.yaml -> components/renovate/manifests/
#       renovate/renovate-token (RENOVATE_TOKEN): lets Renovate open pull requests.
#       Fine-grained PAT, repositories platform-gitops and sample-app, permissions
#       Read and write: Contents, Pull requests, Issues, Workflows, Commit statuses;
#       Read: Dependabot alerts (Metadata: read is added automatically).
#
# Make both at https://github.com/settings/personal-access-tokens (expiry: up to a year;
# re-run this script with new tokens before they expire). Only this cluster can decrypt
# the files, so they're safe in the public repo.
set -euo pipefail
trap 'echo "FAILED at line $LINENO - check the files in ~/ci-sealed before copying them" >&2' ERR

OUT="$HOME/ci-sealed"
mkdir -p "$OUT"

header() {
  echo "# $1, encrypted with Sealed Secrets."
  echo "# Generated by scripts/seal-ci-secrets.sh - only this cluster can decrypt it."
}

read -rsp "ARC token (sample-app, Administration read/write): " ARC_TOKEN; echo
read -rsp "Renovate token (platform-gitops + sample-app): " RENOVATE_TOKEN; echo
[[ -n "$ARC_TOKEN" && -n "$RENOVATE_TOKEN" ]] || { echo "Both tokens are needed" >&2; exit 1; }

# Check the tokens work before sealing them.
for t in ARC_TOKEN RENOVATE_TOKEN; do
  code=$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer ${!t}" \
    https://api.github.com/repos/andrewsgitacc/sample-app)
  [[ "$code" == 200 ]] || { echo "$t can't read andrewsgitacc/sample-app (HTTP $code)" >&2; exit 1; }
done
echo "Both tokens can read sample-app."

{
  header "ARC's GitHub token for sample-app"
  kubectl create secret generic arc-github-token --namespace arc-runners \
    --from-literal=github_token="$ARC_TOKEN" --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/github-token-sealedsecret.yaml"

{
  header "Renovate's GitHub token"
  kubectl create secret generic renovate-token --namespace renovate \
    --from-literal=RENOVATE_TOKEN="$RENOVATE_TOKEN" --dry-run=client -o yaml | kubeseal --format yaml
} > "$OUT/renovate-token-sealedsecret.yaml"

unset ARC_TOKEN RENOVATE_TOKEN
ls -l "$OUT"

cat <<'MSG'

Next, on the Mac (on your branch), one scp for both files:
  cd ~/GitHub/platform-gitops
  scp -r admin@172.16.79.10:ci-sealed /tmp/
  cp /tmp/ci-sealed/github-token-sealedsecret.yaml components/arc-sample-app/manifests/
  cp /tmp/ci-sealed/renovate-token-sealedsecret.yaml components/renovate/manifests/
  rm -rf /tmp/ci-sealed
  then commit and push - and merge only once the pull request shows that commit.
MSG
